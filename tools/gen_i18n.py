#!/usr/bin/env python3
"""Generate windline/i18n.go from the upstream Apple .strings files.

Usage:
    python tools/gen_i18n.py [resources_root]

`resources_root` defaults to the upstream Tendedero resources directory and must
contain one <code>.lproj/Localizable.strings file per supported language. The
generated Go file is written to the repo root (the parent of this script's
directory), i.e. <repo>/i18n.go.

The English file is the source of truth for the key set; every other language
contributes the keys its own file defines. Because L falls back to the English
text, a translation file that omits a key is still correct - the key is simply
left out of that language's map.

The layout is canonicalised with gofmt when it is available, so the output is
gofmt-clean by construction.
"""

from __future__ import annotations

import os
import re
import shutil
import subprocess
import sys

DEFAULT_RESOURCES = (
    r"D:\AI\tes\_upstream_tendedero\Sources\Tendedero\Resources"
)

# Display order of supportedLanguages; English is the source language and never
# gets an entry in the translations map.
LANGUAGES = ["en", "es", "gl", "fr", "pt-BR", "ja", "ko", "zh-Hans", "tr", "az"]

# "key" = "value";  with either side allowed to contain backslash escapes.
ENTRY_RE = re.compile(r'^\s*"((?:\\.|[^"\\])*)"\s*=\s*"((?:\\.|[^"\\])*)"\s*;\s*$')
BLOCK_COMMENT_RE = re.compile(r"/\*.*?\*/", re.S)
HEX4_RE = re.compile(r"[0-9a-fA-F]{4}")
REPLACEMENT = "\ufffd"

HEADER = "// Code generated by tools/gen_i18n.py from the upstream .strings files. DO NOT EDIT."


def _split_surrogate(text: str, start: int) -> tuple[str, int] | None:
    """Consume the `\\uXXXX` (high surrogate) + `\\uXXXX` (low) pair at start."""
    hi = HEX4_RE.match(text, start + 2)
    if not hi:
        return None
    high = int(hi.group(0), 16)
    if not 0xD800 <= high <= 0xDBFF:
        return None
    lo_at = hi.end()
    if text[lo_at:lo_at + 2] != "\\u":
        return None
    lo = HEX4_RE.match(text, lo_at + 2)
    if not lo:
        return None
    low = int(lo.group(0), 16)
    if not 0xDC00 <= low <= 0xDFFF:
        return None
    combined = 0x10000 + ((high - 0xD800) << 10) + (low - 0xDC00)
    return chr(combined), lo.end()


def _chr(digits: str) -> str:
    r"""chr() for a \u / \U escape; lone surrogates cannot be encoded, so degrade."""
    code = int(digits, 16)
    if 0xD800 <= code <= 0xDFFF:
        return REPLACEMENT
    return chr(code)


def unescape(text: str) -> str:
    """Resolve the escapes Apple's .strings format allows.

    Handles \\" \\\\ \\n \\t \\r \\0, \\uxxxx (BMP) and \\Uxxxx / \\Uxxxxxxxx, plus
    \\uXXXX surrogate pairs. A malformed escape degrades to U+FFFD rather than
    raising, so generation never dies on a stray backslash.
    """
    out = []
    i = 0
    while i < len(text):
        ch = text[i]
        if ch != "\\":
            out.append(ch)
            i += 1
            continue
        nxt = text[i + 1] if i + 1 < len(text) else ""
        if nxt in '"\\':
            out.append(nxt)
            i += 2
        elif nxt == "n":
            out.append("\n")
            i += 2
        elif nxt == "t":
            out.append("\t")
            i += 2
        elif nxt == "r":
            out.append("\r")
            i += 2
        elif nxt == "0":
            out.append("\0")
            i += 2
        elif nxt == "u":
            pair = _split_surrogate(text, i)
            hex4 = HEX4_RE.match(text, i + 2)
            if pair:
                out.append(pair[0])
                i = pair[1]
            elif hex4:
                out.append(_chr(hex4.group(0)))
                i = hex4.end()
            else:
                out.append(REPLACEMENT)
                i += 2
        elif nxt == "U":
            # Apple consumers (CFPropertyList / plistlib) read \U exactly like
            # \u: four hex digits, no 8-digit form.
            hex4 = HEX4_RE.match(text, i + 2)
            if hex4:
                out.append(_chr(hex4.group(0)))
                i = hex4.end()
            else:
                out.append(REPLACEMENT)
                i += 2
        else:
            # Unknown escape: keep the character, drop the useless backslash.
            out.append(nxt if nxt else REPLACEMENT)
            i += 2 if nxt else 1
    return "".join(out)


def parse_strings(path: str) -> list[tuple[str, str]]:
    """Return the (key, value) pairs of one Localizable.strings file."""
    with open(path, encoding="utf-8-sig") as fh:
        text = fh.read()
    text = BLOCK_COMMENT_RE.sub("", text)
    pairs: list[tuple[str, str]] = []
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("//"):
            continue
        m = ENTRY_RE.match(line)
        if m:
            pairs.append((unescape(m.group(1)), unescape(m.group(2))))
        else:
            print(f"warning: unparsed line in {path}: {line!r}", file=sys.stderr)
    return pairs


def go_quote(text: str) -> str:
    """Quote text as a Go interpreted string literal."""
    out = ['"']
    for ch in text:
        code = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        elif code < 0x20 or code == 0x7F:
            out.append("\\x%02x" % code)
        else:
            out.append(ch)  # printable non-ASCII stays literal UTF-8
    out.append('"')
    return "".join(out)


def render(langs: dict[str, list[tuple[str, str]]]) -> str:
    lines = [
        HEADER,
        "",
        "package main",
        "",
        "var supportedLanguages = []string{%s}"
        % ", ".join(go_quote(lang) for lang in LANGUAGES if lang in langs),
        "",
        'var currentLanguage = "en"',
        "",
        "var translations = map[string]map[string]string{",
    ]
    for lang in LANGUAGES:
        if lang == "en" or lang not in langs:
            continue
        lines.append("\t%s: {" % go_quote(lang))
        for key, value in langs[lang]:
            lines.append("\t\t%s: %s," % (go_quote(key), go_quote(value)))
        lines.append("\t},")
    lines += [
        "}",
        "",
        "// L returns the English text translated into the current language, falling",
        "// back to the English text itself.",
        "func L(english string) string {",
        "\tif m, ok := translations[currentLanguage]; ok {",
        "\t\tif s, ok := m[english]; ok {",
        "\t\t\treturn s",
        "\t\t}",
        "\t}",
        "\treturn english",
        "}",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    resources = os.path.abspath(argv[1]) if len(argv) > 1 else DEFAULT_RESOURCES
    repo_root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out_path = os.path.join(repo_root, "i18n.go")

    langs: dict[str, list[tuple[str, str]]] = {}
    for lang in LANGUAGES:
        path = os.path.join(resources, f"{lang}.lproj", "Localizable.strings")
        if not os.path.exists(path):
            print(f"warning: no strings file for {lang}: {path}", file=sys.stderr)
            continue
        langs[lang] = parse_strings(path)

    if "en" not in langs:
        print(f"error: English strings not found under {resources}", file=sys.stderr)
        return 1

    with open(out_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(render(langs))

    gofmt = shutil.which("gofmt")
    if gofmt:
        subprocess.run([gofmt, "-w", out_path], check=True)
    else:
        print("warning: gofmt not on PATH; layout may not be canonical", file=sys.stderr)

    en_keys = [key for key, _ in langs["en"]]
    en_set = set(en_keys)
    print(f"wrote {out_path}")
    print(f"en: {len(en_keys)} keys")
    for lang in LANGUAGES:
        if lang == "en" or lang not in langs:
            continue
        keys = [key for key, _ in langs[lang]]
        missing = [key for key in en_keys if key not in set(keys)]
        extra = [key for key in keys if key not in en_set]
        print(f"{lang}: {len(keys)} entries ({len(missing)} missing, {len(extra)} extra)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
